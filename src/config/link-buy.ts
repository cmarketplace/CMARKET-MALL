/**
 * «링크로 바로 사기» 스위치 — URL 하나로 사진·제품명·규격·판매가를 읽어 세모 물품으로 등록하고, 판매 금액을 자동으로 정해
 * 장바구니 → 씨마켓 구매대행 주문까지 잇는다(대표 2026-10-21 «세모네모에 url만 넣으면 … 판매금액 자동 책정»).
 *
 * **기본은 꺼짐**이다. 이 몰은 main 머지가 곧 Vercel 운영 배포라, 꺼져 있으면 «링크로 사기» 화면이 지금과 같다
 * (담당자에게 맡기는 요청 양식) — `/api/shop/link-items/*` 는 404.
 *
 * 켜는 법: Vercel 환경변수 `SHOP_LINK_BUY=1` → 재배포. **세모 URL 담기 엔진(세모 PR #1530)이 운영에 나가고, 세모 관리자에서
 * 이 몰의 «대신 사 드림» 판매자를 정한 뒤** 켠다 — 먼저 켜면 담기가 세모 404/409 로 막힌다(화면은 그 문구를 그대로 보인다).
 *
 * 서버 전용 값이다(`NEXT_PUBLIC_` 아님). 클라이언트는 레이아웃이 내려 주는 값(ShopProvider)으로만 안다.
 */
export function linkBuyEnabled(): boolean {
  return process.env.SHOP_LINK_BUY?.trim() === '1'
}
